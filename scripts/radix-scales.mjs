// Radix Colors (https://www.radix-ui.com/colors) ships a light file and a dark file per scale, and the dark one
// only applies under a `.dark` class. This joins them into one file with `light-dark()`, so that the page's
// `color-scheme` (the system's, or the choice made in the editor) picks the steps with no JavaScript at all.
// Writes src/radix-scales.css. Run by `npm run sync-helper`.
import {readFileSync, writeFileSync, existsSync} from 'node:fs'

const SCALES = ['slate', 'indigo', 'red', 'green', 'amber', 'purple', 'cyan', 'orange']
const ALPHA_ONLY = ['black', 'white']
const dir = new URL('../node_modules/@radix-ui/colors/', import.meta.url)

/** The variables of a Radix Colors file: [srgb, display-p3]. */
function read(file) {
	const [srgb, p3 = ''] = readFileSync(new URL(file, dir), 'utf8').split('@supports')
	const vars = text =>
		Object.fromEntries([...text.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)].map(match => [match[1], match[2]]))
	return [vars(srgb), vars(p3)]
}

const srgb = []
const p3 = []
for (const name of SCALES) {
	for (const suffix of ['', '-alpha']) {
		const [light, lightP3] = read(`${name}${suffix}.css`)
		const [dark, darkP3] = read(`${name}-dark${suffix}.css`)
		for (const variable of Object.keys(light)) {
			srgb.push(`--${variable}: light-dark(${light[variable]}, ${dark[variable]});`)
			p3.push(`--${variable}: light-dark(${lightP3[variable]}, ${darkP3[variable]});`)
		}
	}
}
for (const name of ALPHA_ONLY) {
	const [vars, varsP3] = read(`${name}-alpha.css`)
	for (const variable of Object.keys(vars)) {
		srgb.push(`--${variable}: ${vars[variable]};`)
		p3.push(`--${variable}: ${varsP3[variable]};`)
	}
}

const indent = (lines, tabs) => lines.map(line => '\t'.repeat(tabs) + line).join('\n')
const css = `/* Generated by scripts/radix-scales.mjs from @radix-ui/colors. Do not edit. */
:root {
${indent(srgb, 1)}
}

@supports (color: color(display-p3 1 1 1)) {
	@media (color-gamut: p3) {
		:root {
${indent(p3, 3)}
		}
	}
}
`
const target = new URL('../src/radix-scales.css', import.meta.url)
if (!existsSync(target) || readFileSync(target, 'utf8') !== css) writeFileSync(target, css)
